"""SYNTHETIC gesture landmark generator.

*** FOR PIPELINE TESTING ONLY. THESE DATA ARE FAKE. ***
*** NEVER use them (or models/metrics derived from them) in the report. ***

Usage:
    python -m brain.gestures.make_synthetic --out <dir>

Generates 4 fake persons x 5 labels of plausible-looking MediaPipe landmark
sequences (same CSV contract as the real dataset) plus a ``SYNTHETIC_README.txt``
marker. Persons are named ``synth1..synth4`` so they can never be mistaken for
the real team members.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from . import LABELS
from .features import (
    CSV_COLUMNS,
    L_ELBOW,
    L_HIP,
    L_SHOULDER,
    L_WRIST,
    NOSE,
    NUM_LANDMARKS,
    R_ELBOW,
    R_HIP,
    R_SHOULDER,
    R_WRIST,
)

N_PERSONS = 4
FRAMES_PER_FILE = 120
README = (
    "SYNTHETIC DATA - generated by brain.gestures.make_synthetic.\n"
    "Only for testing the training pipeline. Do NOT use for the report or the demo.\n"
)


def make_person_params(rng: np.random.Generator) -> dict:
    """Per-person body size, position and gesture style (so persons differ)."""
    return {
        "scale": rng.uniform(0.8, 1.3),  # distance to camera
        "cx": rng.uniform(0.42, 0.58),
        "sy": rng.uniform(0.36, 0.46),  # shoulder height in the image
        "angle_bias": rng.normal(0.0, 6.0),
        "hips_missing_prob": rng.choice([0.0, 0.0, 0.1]),
    }


def _dir(side: int, angle_deg: float) -> np.ndarray:
    """Unit vector; 0 deg = hanging down, 90 = horizontal outward, 180 = up."""
    a = np.radians(angle_deg)
    return np.array([side * np.sin(a), np.cos(a)])


def _arm_angles(label: str, rng: np.random.Generator, bias: float) -> dict:
    """(upper_angle, fore_angle) per side; side +1 = person's left, -1 = right."""
    j = lambda s: rng.normal(0.0, s)  # noqa: E731
    down = {"u": 10 + j(6), "f": 8 + j(8)}
    if label == "ADVANCE":
        return {s: {"u": 150 + bias + j(8), "f": 172 + j(8)} for s in (1, -1)}
    if label == "STOP":
        return {s: {"u": 35 + bias + j(6), "f": -105 + j(8)} for s in (1, -1)}
    if label == "TURN_LEFT":
        return {1: {"u": 90 + bias + j(7), "f": 90 + j(9)}, -1: down}
    if label == "TURN_RIGHT":
        return {-1: {"u": 90 + bias + j(7), "f": 90 + j(9)}, 1: down}
    raise ValueError(label)


def _none_targets(rng: np.random.Generator) -> dict:
    """Random relaxed / natural pose for the NONE class."""
    mode = rng.integers(0, 3)
    if mode == 0:  # relaxed
        return {s: {"u": 10 + rng.normal(0, 8), "f": 10 + rng.normal(0, 12)} for s in (1, -1)}
    if mode == 1:  # one arm doing something (scratching, holding, waving low)
        side = int(rng.choice([1, -1]))
        t = {s: {"u": 10 + rng.normal(0, 6), "f": 8 + rng.normal(0, 10)} for s in (1, -1)}
        t[side] = {"u": rng.uniform(20, 75), "f": rng.uniform(-20, 120)}
        return t
    return {s: {"u": rng.uniform(0, 70), "f": rng.uniform(-30, 100)} for s in (1, -1)}  # random


def generate_landmarks(label: str, rng: np.random.Generator, params: dict, n_frames: int = FRAMES_PER_FILE) -> np.ndarray:
    """Return an array (n_frames, 33, 4) of synthetic landmarks for one label."""
    u = 0.18 * params["scale"]  # shoulder width in normalized x
    cx, sy = params["cx"], params["sy"]
    bias = params["angle_bias"]

    if label == "NONE":
        current = _none_targets(rng)
        target = _none_targets(rng)
        next_change = int(rng.integers(20, 40))
    else:
        base = _arm_angles(label, rng, bias)

    frames = np.zeros((n_frames, NUM_LANDMARKS, 4))
    for t in range(n_frames):
        if label == "NONE":
            if t == next_change:
                current, target = target, _none_targets(rng)
                next_change += int(rng.integers(20, 40))
            arms = current
        else:
            arms = {s: {k: v + rng.normal(0, 2.5) for k, v in base[s].items()} for s in (1, -1)}

        lm = np.zeros((NUM_LANDMARKS, 4))
        center = np.array([cx + rng.normal(0, 0.004), sy + 0.9 * u * 1.0])
        # Default every landmark near the body center, then place the real ones.
        lm[:, 0] = center[0] + rng.normal(0, 0.01, NUM_LANDMARKS)
        lm[:, 1] = center[1] + rng.normal(0, 0.01, NUM_LANDMARKS)
        lm[:, 2] = rng.normal(0, 0.05, NUM_LANDMARKS)
        lm[:, 3] = np.clip(rng.normal(0.95, 0.03, NUM_LANDMARKS), 0.0, 1.0)

        sh_l = np.array([cx + 0.5 * u, sy])
        sh_r = np.array([cx - 0.5 * u, sy])
        lm[NOSE, :2] = [cx, sy - 0.9 * u]
        lm[L_SHOULDER, :2], lm[R_SHOULDER, :2] = sh_l, sh_r
        lm[L_HIP, :2] = [cx + 0.4 * u, sy + 1.9 * u]
        lm[R_HIP, :2] = [cx - 0.4 * u, sy + 1.9 * u]
        for side, sh, elbow_i, wrist_i in ((1, sh_l, L_ELBOW, L_WRIST), (-1, sh_r, R_ELBOW, R_WRIST)):
            elbow = sh + 1.0 * u * _dir(side, arms[side]["u"])
            wrist = elbow + 0.9 * u * _dir(side, arms[side]["f"])
            lm[elbow_i, :2] = elbow
            lm[wrist_i, :2] = wrist
        # Legs, just to look like a full body.
        for idx, (dx, dy) in {25: (0.4, 3.4), 26: (-0.4, 3.4), 27: (0.4, 4.9), 28: (-0.4, 4.9)}.items():
            lm[idx, :2] = [cx + dx * u, sy + dy * u]

        lm[:, :2] += rng.normal(0, 0.003, (NUM_LANDMARKS, 2))
        if rng.random() < params["hips_missing_prob"]:
            lm[[L_HIP, R_HIP], 3] = 0.2  # exercises the shoulder-midpoint fallback
        frames[t] = lm
    return frames


def generate_dataset(out_dir: Path, seed: int = 0, n_persons: int = N_PERSONS, frames: int = FRAMES_PER_FILE) -> list[Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "SYNTHETIC_README.txt").write_text(README)
    rng = np.random.default_rng(seed)
    paths = []
    for p in range(1, n_persons + 1):
        person = f"synth{p}"
        params = make_person_params(rng)
        for k, label in enumerate(LABELS):
            # Two takes per label so GroupKFold has enough frames per person.
            for take in range(2):
                lms = generate_landmarks(label, rng, params, frames)
                df = pd.DataFrame(lms.reshape(len(lms), -1), columns=CSV_COLUMNS[2:])
                df.insert(0, "label", label)
                df.insert(0, "person", person)
                path = out_dir / f"{person}_{label}_20000101_0000{p}{k}{take}.csv"
                df.to_csv(path, index=False)
                paths.append(path)
    return paths


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m brain.gestures.make_synthetic",
        description="Generate SYNTHETIC gesture landmark CSVs for pipeline testing ONLY (never for the report).",
    )
    parser.add_argument("--out", required=True, help="Output directory (use a temp dir, NOT data/gestures).")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--frames", type=int, default=FRAMES_PER_FILE, help="Frames per file.")
    args = parser.parse_args(argv)
    paths = generate_dataset(Path(args.out), seed=args.seed, frames=args.frames)
    print(f"Wrote {len(paths)} SYNTHETIC files to {args.out} (testing only; do not use for the report).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
