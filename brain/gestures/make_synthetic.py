"""SYNTHETIC hand-landmark generator.

*** FOR PIPELINE TESTING ONLY. THESE DATA ARE FAKE. ***
*** NEVER use them (or models/metrics derived from them) in the report. ***

Usage:
    python -m brain.gestures.make_synthetic --out <dir>

Generates 4 fake persons x every label (2 takes each) of plausible-looking
MediaPipe Hands landmark sequences (same CSV contract as the real dataset)
plus a ``SYNTHETIC_README.txt`` marker. Persons are named ``synth1..synth4`` so
they can never be mistaken for the real team members. Odd persons use the
"Right" label and even persons the "Left" one, so both handedness values are
present.

The hand is a tiny kinematic model in palm units (wrist -> middle MCP = 1):
fingers are rigid axes whose segments are shortened by ``cos(cumulative
flexion)`` (curling happens towards the camera), the thumb is a 3-segment
in-plane chain, and the whole hand is rotated by a roll angle (0 = fingers
up, +90 = fingers point to the image's right).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from . import LABELS
from .features import CSV_COLUMNS, NUM_LANDMARKS

N_PERSONS = 4
FRAMES_PER_FILE = 120
README = (
    "SYNTHETIC DATA - generated by brain.gestures.make_synthetic.\n"
    "Only for testing the training pipeline. Do NOT use for the report or the demo.\n"
)

# Hand skeleton in palm units, x to the right, y UP, for the "Right" label
# (thumb on the -x side). Order: index, middle, ring, pinky.
_MCP = np.array([[-0.30, 0.95], [0.00, 1.00], [0.28, 0.93], [0.52, 0.80]])
_SEG = np.array([[0.45, 0.28, 0.22], [0.50, 0.30, 0.23], [0.45, 0.28, 0.22], [0.36, 0.20, 0.18]])
_THUMB_CMC = np.array([-0.30, 0.25])
_THUMB_SEG = np.array([0.45, 0.40, 0.35])

_CURL = (80.0, 100.0, 60.0)  # MCP, PIP, DIP flexion of a closed finger (degrees)
_EXT = (3.0, 3.0, 3.0)
_THUMB_UP = (-8.0, -4.0, -4.0)  # in-plane direction of each thumb segment (deg from "up", + = to +x)
_THUMB_OUT = (-50.0, -55.0, -55.0)
_THUMB_TUCKED = (20.0, 60.0, 140.0)
_THUMB_ASIDE = (-35.0, -30.0, -25.0)
_SPREAD_REST = (-5.0, 0.0, 4.0, 10.0)
_SPREAD_WIDE = (-14.0, -4.0, 6.0, 18.0)
_SPREAD_V = (-14.0, 6.0, 6.0, 12.0)


def _spec(thumb, flex, spread, roll) -> dict:
    return {"thumb": thumb, "flex": [tuple(f) for f in flex], "spread": spread, "roll": float(roll)}


def _mean_spec(label: str) -> dict:
    """Noise-free parameters of each gesture."""
    if label == "THUMBS_UP":
        return _spec(_THUMB_UP, [_CURL] * 4, _SPREAD_REST, 0.0)
    if label == "OPEN_PALM":
        return _spec(_THUMB_OUT, [_EXT] * 4, _SPREAD_WIDE, 0.0)
    if label == "POINT_LEFT":  # person points to THEIR left = image right (+x)
        return _spec(_THUMB_TUCKED, [_EXT, _CURL, _CURL, _CURL], _SPREAD_REST, 90.0)
    if label == "POINT_RIGHT":
        return _spec(_THUMB_TUCKED, [_EXT, _CURL, _CURL, _CURL], _SPREAD_REST, -90.0)
    if label == "VICTORY":
        return _spec(_THUMB_TUCKED, [_EXT, _EXT, _CURL, _CURL], _SPREAD_V, 0.0)
    if label == "FIST":
        return _spec(_THUMB_TUCKED, [_CURL] * 4, _SPREAD_REST, 0.0)
    if label == "LOVE_YOU":  # thumb + index + pinky out, middle and ring curled
        return _spec(_THUMB_OUT, [_EXT, _CURL, _CURL, _EXT], _SPREAD_WIDE, 0.0)
    raise ValueError(label)


def _none_spec(rng: np.random.Generator) -> dict:
    """Random relaxed / natural hand for the NONE class."""
    if rng.random() < 0.7:  # relaxed, half-curled fingers
        flex = [(rng.uniform(10, 35), rng.uniform(10, 40), rng.uniform(5, 25)) for _ in range(4)]
        thumb = tuple(a + rng.normal(0, 8) for a in _THUMB_ASIDE)
        return _spec(thumb, flex, _SPREAD_REST, rng.normal(0, 35))
    flex = [(rng.uniform(0, 85), rng.uniform(0, 100), rng.uniform(0, 60)) for _ in range(4)]
    thumb = tuple(rng.uniform(-60, 60) for _ in range(3))
    return _spec(thumb, flex, _SPREAD_REST, rng.normal(0, 50))


def build_hand(spec: dict, handedness: str, palm: float, center, finger_scale: float = 1.0) -> np.ndarray:
    """Landmarks (21, 3) in normalized image coordinates for one hand pose.

    ``center`` is the wrist position in the image; ``palm`` the wrist -> middle
    MCP distance (== ``hand_size``).
    """
    if handedness not in ("Left", "Right"):
        raise ValueError(f"handedness must be 'Left' or 'Right', got {handedness!r}")
    local = np.zeros((NUM_LANDMARKS, 2))  # x right, y up, palm units
    # Thumb chain (landmarks 1..4).
    pos = _THUMB_CMC.copy()
    local[1] = pos
    for k in range(3):
        a = np.radians(spec["thumb"][k])
        pos = pos + finger_scale * _THUMB_SEG[k] * np.array([np.sin(a), np.cos(a)])
        local[2 + k] = pos
    # Four fingers (landmarks 5..20).
    for f in range(4):
        axis_a = np.radians(spec["spread"][f])
        axis = np.array([np.sin(axis_a), np.cos(axis_a)])
        pos = _MCP[f].copy()
        local[5 + 4 * f] = pos
        cum = 0.0
        for j in range(3):
            cum += np.radians(spec["flex"][f][j])
            pos = pos + finger_scale * _SEG[f, j] * np.cos(cum) * axis
            local[6 + 4 * f + j] = pos
    if handedness == "Left":
        local[:, 0] *= -1.0
    r = np.radians(spec["roll"])
    x = local[:, 0] * np.cos(r) + local[:, 1] * np.sin(r)
    y = -local[:, 0] * np.sin(r) + local[:, 1] * np.cos(r)
    out = np.zeros((NUM_LANDMARKS, 3))
    out[:, 0] = center[0] + palm * x
    out[:, 1] = center[1] - palm * y  # image y grows downward
    return out


def mean_hand(label: str, handedness: str = "Right", palm: float = 0.1, center=(0.5, 0.5)) -> np.ndarray:
    """Noise-free landmarks (21, 3) of a gesture (NONE = relaxed hand). Handy for tests."""
    if label == "NONE":
        spec = _spec(_THUMB_ASIDE, [(20.0, 25.0, 15.0)] * 4, _SPREAD_REST, 0.0)
    else:
        spec = _mean_spec(label)
    return build_hand(spec, handedness, palm, center)


def make_person_params(rng: np.random.Generator, handedness: str = "Right") -> dict:
    """Per-person hand size, position, proportions and habitual hand."""
    return {
        "handedness": handedness,
        "palm": rng.uniform(0.07, 0.15),  # distance to camera
        "cx": rng.uniform(0.35, 0.65),
        "cy": rng.uniform(0.50, 0.70),  # wrist position (hand is above it)
        "roll_bias": rng.normal(0.0, 4.0),
        "finger_scale": rng.uniform(0.92, 1.08),
    }


def _jitter(spec: dict, rng: np.random.Generator, roll_bias: float) -> dict:
    return {
        "thumb": tuple(a + rng.normal(0, 7) for a in spec["thumb"]),
        "flex": [tuple(v + rng.normal(0, 6) for v in f) for f in spec["flex"]],
        "spread": tuple(a + rng.normal(0, 2.5) for a in spec["spread"]),
        "roll": spec["roll"] + roll_bias + rng.normal(0, 7),
    }


def generate_landmarks(label: str, rng: np.random.Generator, params: dict, n_frames: int = FRAMES_PER_FILE) -> np.ndarray:
    """Return an array (n_frames, 21, 3) of synthetic landmarks for one label."""
    hand = params["handedness"]
    if label == "NONE":
        spec = _none_spec(rng)
        next_change = int(rng.integers(20, 40))
    else:
        spec = _mean_spec(label)

    frames = np.zeros((n_frames, NUM_LANDMARKS, 3))
    for t in range(n_frames):
        if label == "NONE" and t == next_change:
            spec = _none_spec(rng)
            next_change += int(rng.integers(20, 40))
        frame_spec = _jitter(spec, rng, params["roll_bias"])
        palm = params["palm"] * rng.uniform(0.97, 1.03)
        center = (params["cx"] + rng.normal(0, 0.01), params["cy"] + rng.normal(0, 0.01))
        lm = build_hand(frame_spec, hand, palm, center, params["finger_scale"])
        lm[:, :2] += rng.normal(0, 0.0015, (NUM_LANDMARKS, 2))
        lm[:, 2] = rng.normal(0, 0.02, NUM_LANDMARKS)
        frames[t] = lm
    return frames


def generate_dataset(out_dir: Path, seed: int = 0, n_persons: int = N_PERSONS, frames: int = FRAMES_PER_FILE) -> list[Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "SYNTHETIC_README.txt").write_text(README)
    rng = np.random.default_rng(seed)
    paths = []
    for p in range(1, n_persons + 1):
        person = f"synth{p}"
        handedness = "Right" if p % 2 == 1 else "Left"
        params = make_person_params(rng, handedness)
        for k, label in enumerate(LABELS):
            # Two takes per label so GroupKFold has enough frames per person.
            for take in range(2):
                lms = generate_landmarks(label, rng, params, frames)
                df = pd.DataFrame(lms.reshape(len(lms), -1), columns=CSV_COLUMNS[3:])
                df.insert(0, "handedness", handedness)
                df.insert(0, "label", label)
                df.insert(0, "person", person)
                path = out_dir / f"{person}_{label}_20000101_0000{p}{k}{take}.csv"
                df.to_csv(path, index=False)
                paths.append(path)
    return paths


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m brain.gestures.make_synthetic",
        description="Generate SYNTHETIC hand landmark CSVs for pipeline testing ONLY (never for the report).",
    )
    parser.add_argument("--out", required=True, help="Output directory (use a temp dir, NOT data/gestures).")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--frames", type=int, default=FRAMES_PER_FILE, help="Frames per file.")
    args = parser.parse_args(argv)
    paths = generate_dataset(Path(args.out), seed=args.seed, frames=args.frames)
    print(f"Wrote {len(paths)} SYNTHETIC files to {args.out} (testing only; do not use for the report).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
